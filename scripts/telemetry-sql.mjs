#!/usr/bin/env node
// Writes the production paste for the telemetry tables (supabase/migrations/20261106000000_rework.sql section 10) as a
// file of its own, so production never re-runs the whole rework file mid-event (design/references/observability-design.md
// §2 and §7; HANDOFF.md "Telemetry in production"):
//
//   node scripts/telemetry-sql.mjs [dir]      (default /tmp/observability)
//     <dir>/migration.sql   begin; preflight; section 10; notify; commit;   ← paste this to apply
//     <dir>/dry-run.sql     the same, ending in rollback;                     ← paste this first: nothing is kept
//
// Reads the repo only; never connects to a database.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const REWORK = join(ROOT, 'supabase/migrations/20261106000000_rework.sql');
const START = '-- 10. Telemetry';
const END = '-- (end of section 10)';

/** Section 10 of the rework file, from its rule line to its end marker. */
export function telemetrySection(sql = readFileSync(REWORK, 'utf8')) {
  const at = sql.indexOf(START);
  const end = sql.indexOf(END);
  if (at < 0 || end < at) throw new Error('telemetry-sql: section 10 not found in the rework file');
  const ruleStart = sql.lastIndexOf('\n-- ---', at);
  return sql.slice(ruleStart + 1, end + END.length).trimEnd() + '\n';
}

const HEADER = `-- =====================================================================================================
-- Telemetry (lp_tel_*), the production paste. Generated by scripts/telemetry-sql.mjs from
-- supabase/migrations/20261106000000_rework.sql section 10 (the same statements; do not edit by hand).
--
-- How to apply (Supabase dashboard → SQL Editor, as postgres), BEFORE deploying the build that sends telemetry:
--   1. Dry run: paste dry-run.sql (this file ending in rollback;). It must finish without an error; the NOTICE says
--      "lp-tel-retention: scheduled daily 09:17 UTC (job …)". Nothing is kept.
--   2. Commit: paste migration.sql (ending in commit;).
--   3. Check: select enabled, off_at from public.lp_tel_settings;  → t | 2026-11-10 11:00:00+00
-- It takes no lock on any existing table (every table is new) and is safe to paste twice.
-- Kill switch: update public.lp_tel_settings set enabled = false, updated_at = now();
-- =====================================================================================================

begin;

set local lock_timeout = '5s';
set local statement_timeout = '60s';

do $preflight$
begin
  if current_setting('server_version_num')::int < 140000 then
    raise exception 'Preflight failed: PostgreSQL 14 or newer is required (found %).', current_setting('server_version');
  end if;
  if to_regclass('public.lp_push_subscriptions') is null then
    raise exception 'Preflight failed: public.lp_push_subscriptions is missing (the F4 section of the rework file is not applied).';
  end if;
end
$preflight$;

`;

/** The paste: header, preflight, section 10, then commit (or rollback for the dry run). */
export function telemetryPaste(end = 'commit') {
  return `${HEADER}${telemetrySection()}\nnotify pgrst, 'reload schema';\n\n${end};\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const dir = process.argv[2] || '/tmp/observability';
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, 'migration.sql'), telemetryPaste('commit'));
  writeFileSync(join(dir, 'dry-run.sql'), telemetryPaste('rollback'));
  console.log(`telemetry-sql: wrote ${join(dir, 'migration.sql')} and ${join(dir, 'dry-run.sql')}`);
}
